# calculate even numbers
print("even and odd numbers from 1 to 100: ")
for i in range(100):
    if i%2==0:
        print("even numbers: ",i)
# calculate odd numbers
for i in range(100):
    if i%2!=0:
        print("Odd numbers: ",i)